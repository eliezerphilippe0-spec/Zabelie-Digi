export const FACTURATION: Record<Lang, FacturationCopy> = { fr, ht, en, es };

/** Langue d'affichage des dates : l'ICU n'a pas de données kreyòl, Haïti date en français. */
export const LOCALE_DATE: Record<Lang, string> = { fr: "fr-FR", ht: "fr-HT", en: "en-US", es: "es-ES" };

/** Libellés d'une langue, avec la règle d'arrondi EN VIGUEUR déjà insérée. */
export function facturationCopy(lang: Lang): FacturationCopy {
  const c = FACTURATION[lang] ?? fr;
  const arrondi = ROUNDING_IN_FORCE === "floor" ? c.roundingFloor : c.roundingNearest;
  return { ...c, openBody: c.openBody.replace("{arrondi}", arrondi) };
}
